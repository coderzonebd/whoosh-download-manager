//! Video and audio sites through yt-dlp and ffmpeg (PROTOCOL.md "Media").
//!
//! Only daemons built with media support (desktop and GitHub builds, never
//! a store build) advertise [`MEDIA_CAPABILITY`]; the others answer every
//! `media.*` method with `-32006` (unsupported).

use serde::{Deserialize, Serialize};

use crate::{RequestContext, UnixMillis};

/// Advertised in `HelloResult::capabilities` by daemons with media support.
pub const MEDIA_CAPABILITY: &str = "media";

/// The two helper programs, by their `MediaTool::name`.
pub const TOOL_YT_DLP: &str = "yt-dlp";
pub const TOOL_FFMPEG: &str = "ffmpeg";

fn is_false(b: &bool) -> bool {
    !*b
}

// ---------------------------------------------------------------- media.probe

/// `media.probe`: what a page offers.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MediaProbeParams {
    /// The page (`http` or `https`), e.g. a video's page on a video site.
    pub url: String,
    /// What the browser would send. Only `cookie`, `referer` and `userAgent`
    /// are used; a cookie is only ever one the extension captured for this
    /// URL (the daemon never reads browser cookie stores).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub request: Option<RequestContext>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MediaProbeResult {
    /// The page's canonical URL.
    pub url: String,
    pub title: String,
    /// yt-dlp's extractor name, e.g. "youtube", "generic".
    pub extractor: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub thumbnail: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub duration_secs: Option<u64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub uploader: Option<String>,
    /// A live stream (still running): downloadable only through yt-dlp.
    #[serde(default, skip_serializing_if = "is_false")]
    pub live: bool,
    /// Worst first, best last (yt-dlp's order).
    pub formats: Vec<MediaFormat>,
    pub subtitles: Vec<MediaSubtitle>,
}

/// What a format carries.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum MediaFormatKind {
    /// Video and audio in one file.
    VideoAudio,
    VideoOnly,
    AudioOnly,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MediaFormat {
    /// yt-dlp's format id (`[A-Za-z0-9_.-]`), used in [`MediaChoice::Formats`].
    pub id: String,
    pub kind: MediaFormatKind,
    /// File extension, e.g. "mp4", "webm", "m4a".
    pub ext: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub width: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub height: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub fps: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub vcodec: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub acodec: Option<String>,
    /// Audio bit rate, kbit/s.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub abr_kbps: Option<u32>,
    /// Exact size, or yt-dlp's estimate when `sizeApproximate`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub size_bytes: Option<u64>,
    #[serde(default, skip_serializing_if = "is_false")]
    pub size_approximate: bool,
    /// yt-dlp's note, e.g. "1080p", "medium".
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub note: Option<String>,
    /// Whoosh's engine downloads it (a plain HTTP(S) URL): multi-connection,
    /// resumable, crash-safe. Otherwise yt-dlp downloads it (HLS, DASH
    /// fragments and other streaming protocols).
    pub direct: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MediaSubtitle {
    /// Language code as the site gives it, e.g. "en", "bn", "en-US".
    pub lang: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
    /// Generated by the site (speech recognition), not written by people.
    #[serde(default, skip_serializing_if = "is_false")]
    pub automatic: bool,
}

// ---------------------------------------------------------------- media.add

/// Which formats to download.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum MediaChoice {
    /// The best video with the best audio (merged when they come apart),
    /// at most `maxHeight` pixels high when given.
    #[serde(rename_all = "camelCase")]
    Best {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        max_height: Option<u32>,
    },
    /// The best audio only, kept as it is (`original`) or converted to MP3.
    #[serde(rename_all = "camelCase")]
    Audio {
        #[serde(default)]
        convert: AudioConvert,
    },
    /// Exact format ids from `media.probe`: one, or a video-only and an
    /// audio-only one to merge.
    #[serde(rename_all = "camelCase")]
    Formats { ids: Vec<String> },
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum AudioConvert {
    /// The site's own audio stream (m4a, opus, …), no re-encoding.
    #[default]
    Original,
    Mp3,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MediaAddParams {
    pub url: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub request: Option<RequestContext>,
    pub choice: MediaChoice,
    /// Subtitle languages to save next to the file (`lang` values from
    /// `media.probe`); none when empty.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub subtitles: Vec<String>,
    /// File name without extension; defaults to the title. Sanitized like
    /// any other file name.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub filename: Option<String>,
    /// Absolute directory; defaults to the category's or the global folder.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub directory: Option<String>,
    /// Defaults to `video`, or `music` for audio only.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub category: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub queue: Option<String>,
    #[serde(default = "crate::default_true")]
    pub start: bool,
}

/// `DownloadSummary::media`: present on media downloads only.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MediaDownloadInfo {
    pub title: String,
    /// Short description of the chosen formats, e.g. "1080p mp4",
    /// "audio m4a".
    pub format: String,
    /// Who moves the bytes.
    pub via: MediaVia,
    /// What happens right now, while the download is active.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub step: Option<MediaStep>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum MediaVia {
    /// Whoosh's engine (direct HTTP formats), then ffmpeg merges.
    Engine,
    /// yt-dlp itself (streaming protocols the engine does not speak yet).
    YtDlp,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum MediaStep {
    /// Waiting for yt-dlp or ffmpeg to be fetched (first use).
    PreparingTools,
    /// Asking the site again for fresh links (the old ones expired).
    Refreshing,
    Downloading,
    Subtitles,
    /// ffmpeg joins video and audio (state `verifying`).
    Merging,
    /// ffmpeg converts the audio (state `verifying`).
    Converting,
}

// ---------------------------------------------------------------- media tools

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MediaToolsStatus {
    /// yt-dlp first, then ffmpeg.
    pub tools: Vec<MediaTool>,
    /// Check for updates (and install them) at most once a day.
    pub auto_update: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub last_check_at: Option<UnixMillis>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MediaTool {
    /// [`TOOL_YT_DLP`] or [`TOOL_FFMPEG`].
    pub name: String,
    pub state: MediaToolState,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source: Option<MediaToolSource>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub version: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub path: Option<String>,
    /// From the last update check.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub latest_version: Option<String>,
    #[serde(default, skip_serializing_if = "is_false")]
    pub update_available: bool,
    /// Where updates come from, e.g. "github.com/yt-dlp/yt-dlp".
    pub upstream: String,
    /// The licence of the build that is (or would be) fetched.
    pub license: String,
    /// While `installing`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub downloaded_bytes: Option<u64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub total_bytes: Option<u64>,
    /// The last install or check failure.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum MediaToolState {
    /// Not on this machine yet; fetched on first use.
    Missing,
    Installing,
    Ready,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum MediaToolSource {
    /// Fetched by whoosh into its data directory (and updated by it).
    Managed,
    /// Installed by the system's package manager (Linux, and ffmpeg on
    /// macOS); updated by it, not by whoosh.
    System,
}

