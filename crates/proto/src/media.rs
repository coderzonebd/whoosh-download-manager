#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn choices_are_tagged_by_kind() {
        let c: MediaChoice = serde_json::from_value(json!({ "kind": "best" })).unwrap();
        assert_eq!(c, MediaChoice::Best { max_height: None });
        let c: MediaChoice =
            serde_json::from_value(json!({ "kind": "best", "maxHeight": 720 })).unwrap();
        assert_eq!(
            c,
            MediaChoice::Best {
                max_height: Some(720)
            }
        );
        let c: MediaChoice = serde_json::from_value(json!({ "kind": "audio" })).unwrap();
        assert_eq!(
            c,
            MediaChoice::Audio {
                convert: AudioConvert::Original
            }
        );
        assert_eq!(
            serde_json::to_value(MediaChoice::Formats {
                ids: vec!["137".into(), "140".into()]
            })
            .unwrap(),
            json!({ "kind": "formats", "ids": ["137", "140"] })
        );
        assert_eq!(
            serde_json::to_value(MediaChoice::Audio {
                convert: AudioConvert::Mp3
            })
            .unwrap(),
            json!({ "kind": "audio", "convert": "mp3" })
        );
    }

    #[test]
    fn add_params_default_to_start() {
        let p: MediaAddParams = serde_json::from_value(json!({
            "url": "https://example.com/watch?v=1",
            "choice": { "kind": "best" }
        }))
        .unwrap();
        assert!(p.start);
        assert!(p.subtitles.is_empty());
    }

    #[test]
    fn enums_are_camel_case() {
        assert_eq!(
            serde_json::to_value(MediaFormatKind::VideoAudio).unwrap(),
            json!("videoAudio")
        );
        assert_eq!(
            serde_json::to_value(MediaStep::PreparingTools).unwrap(),
            json!("preparingTools")
        );
        assert_eq!(
            serde_json::to_value(MediaVia::YtDlp).unwrap(),
            json!("ytDlp")
        );
    }
}
